import { useCallback, useEffect, useMemo, useRef, useState, type ReactNode } from 'react';
import {
  Button as MuiButton,
  Card,
  CardContent,
  Chip,
  CircularProgress,
  Dialog,
  DialogActions,
  DialogContent,
  DialogTitle,
  MenuItem,
  Select,
  Table,
  TableBody,
  TableCell,
  TableHead,
  TableRow,
  TextField,
  Tooltip,
} from '@mui/material';
import {
  cloud,
  PLAN_MONTHLY_SECONDS,
  PLAN_YEARLY_SECONDS,
  type AdminCode,
  type AdminUser,
  type CreatedCode,
} from '../cloud/client';
import { Icon } from '../components/Icon';
import { useToast } from '../components/UI';
import { useSubscription } from '../cloud/subscription';
import { messageOf } from '../util';

/**
 * The admin panel.
 *
 * Everything the project knows about licensing is in the hands of an administrator here:
 * who has an account, who is subscribed, until when, which keys are outstanding, and the
 * switch to block an account that should not be using the app at all.
 *
 * Keys are 40-character hex codes generated by the project itself; only their digests are
 * stored, and only the first time is the code ever visible. The panel says so, once, at the
 * moment of generation - after which the admin hands them out.
 */

const KEY_KIND = {
  monthly: { label: 'Premium — Monthly', kind: 'premium' as const, seconds: PLAN_MONTHLY_SECONDS, hint: '31 days from activation' },
  yearly: { label: 'Premium — Yearly', kind: 'premium' as const, seconds: PLAN_YEARLY_SECONDS, hint: '365 days from activation' },
  trial: { label: 'Trial — 7 days', kind: 'trial' as const, seconds: 604800, hint: '7 days from activation' },
  custom: { label: 'Custom duration', kind: 'premium' as const, seconds: 0, hint: 'Any number of days' },
} as const;

type KindKey = keyof typeof KEY_KIND;

function fmtDate(iso: string | null): string {
  if (!iso) return '—';
  const date = new Date(iso);
  if (Number.isNaN(date.getTime())) return '—';
  return date.toLocaleDateString(undefined, { year: 'numeric', month: 'short', day: 'numeric' });
}

function daysLeft(iso: string | null): number | null {
  if (!iso) return null;
  const left = new Date(iso).getTime() - Date.now();
  if (Number.isNaN(left)) return null;
  return Math.ceil(left / 86_400_000);
}

export function AdminPage(): ReactNode {
  const toast = useToast();
  const subscription = useSubscription();
  const [users, setUsers] = useState<AdminUser[] | null>(null);
  const [codes, setCodes] = useState<AdminCode[] | null>(null);
  const [trialClaims, setTrialClaims] = useState(0);
  const [search, setSearch] = useState('');
  const [kind, setKind] = useState<KindKey>('yearly');
  const [days, setDays] = useState(30);
  const [count, setCount] = useState(1);
  const [busy, setBusy] = useState(false);
  const [created, setCreated] = useState<CreatedCode[]>([]);
  const [expiryDialog, setExpiryDialog] = useState<{ user: AdminUser; value: string } | null>(null);
  const loaded = useRef(false);

  const load = useCallback(async () => {
    try {
      const [userList, codeList, claims] = await Promise.all([
        cloud().adminListUsers(),
        cloud().adminListCodes(),
        cloud().adminListTrialClaims(),
      ]);
      setUsers(userList);
      setCodes(codeList);
      setTrialClaims(claims.length);
    } catch (error) {
      toast.error('Admin panel', messageOf(error));
    }
  }, [toast]);

  const isAdmin = subscription.entitlement?.isAdmin === true;

  useEffect(() => {
    if (loaded.current || subscription.loading || !isAdmin) return;
    loaded.current = true;
    void load();
  }, [load, isAdmin, subscription.loading]);

  const stats = useMemo(() => {
    const list = users ?? [];
    const now = Date.now();
    const active = list.filter((user) => user.expiresAt && new Date(user.expiresAt).getTime() > now).length;
    const blocked = list.filter((user) => user.isBlocked).length;
    return { total: list.length, active, trialClaims, blocked };
  }, [users, trialClaims]);

  const visibleUsers = useMemo(() => {
    const needle = search.trim().toLowerCase();
    const list = users ?? [];
    if (!needle) return list;
    return list.filter((user) => user.email.toLowerCase().includes(needle));
  }, [users, search]);

  const outstanding = (codes ?? []).filter((code) => !code.redeemedAt && !code.revokedAt);
  const durationSeconds = kind === 'custom' ? Math.max(1, days) * 86_400 : KEY_KIND[kind].seconds;

  const generate = async () => {
    if (busy) return;
    setBusy(true);
    try {
      const generated = await cloud().adminCreateCodes(KEY_KIND[kind].kind, durationSeconds, Math.min(50, Math.max(1, count)));
      setCreated(generated);
      toast.success(`${generated.length} license key${generated.length === 1 ? '' : 's'} generated`);
      await load();
    } catch (error) {
      toast.error('Could not generate keys', messageOf(error));
    } finally {
      setBusy(false);
    }
  };

  const copy = async (text: string) => {
    try {
      await navigator.clipboard.writeText(text);
      toast.success('Copied to clipboard');
    } catch {
      toast.error('Copy failed', 'Select the key and copy it manually.');
    }
  };

  const saveExpiry = async () => {
    if (!expiryDialog) return;
    const target = new Date(expiryDialog.value);
    if (Number.isNaN(target.getTime())) {
      toast.error('Invalid date', 'Pick a full date and time.');
      return;
    }
    try {
      await cloud().adminSetExpiry(expiryDialog.user.userId, target.toISOString());
      toast.success(`Subscription updated for ${expiryDialog.user.email}`);
      setExpiryDialog(null);
      await load();
    } catch (error) {
      toast.error('Could not update expiry', messageOf(error));
    }
  };

  const extend = async (user: AdminUser, daysToAdd: number) => {
    const base = user.expiresAt && new Date(user.expiresAt).getTime() > Date.now()
      ? new Date(user.expiresAt).getTime()
      : Date.now();
    const next = new Date(base + daysToAdd * 86_400_000);
    try {
      await cloud().adminSetExpiry(user.userId, next.toISOString());
      toast.success(`Extended ${daysToAdd} day${daysToAdd === 1 ? '' : 's'} — now until ${fmtDate(next.toISOString())}`);
      await load();
    } catch (error) {
      toast.error('Could not extend', messageOf(error));
    }
  };

  const toggleBlock = async (user: AdminUser) => {
    try {
      await cloud().adminSetBlocked(user.userId, !user.isBlocked);
      toast.success(user.isBlocked ? `${user.email} can sign in again` : `${user.email} is blocked`);
      await load();
    } catch (error) {
      toast.error('Could not update the account', messageOf(error));
    }
  };

  const revoke = async (code: AdminCode) => {
    try {
      await cloud().adminRevokeCode(code.id);
      toast.success('Key revoked');
      await load();
    } catch (error) {
      toast.error('Could not revoke', messageOf(error));
    }
  };

  if (users === null) {
    return (
      <div className="content">
        <div className="empty">
          <CircularProgress size={26} thickness={4} />
        </div>
      </div>
    );
  }

  // Defence in depth: the rail only offers this page to administrators, but the page itself
  // refuses to issue keys to an account the server does not call one. All hooks above run
  // unconditionally; this is the render gate.
  if (!subscription.loading && !isAdmin) {
    return (
      <div className="content">
        <div className="content-inner">
          <div className="banner err" role="alert" style={{ marginTop: 18 }}>
            <Icon name="lock" />
            <div className="grow">
              <b>Not available for this account</b>
              <div style={{ marginTop: 2 }}>This section is only open to the administrator of the Joe Browser project.</div>
            </div>
          </div>
        </div>
      </div>
    );
  }

  return (
    <div className="content">
      <div className="content-inner">
        <div className="page-head">
          <div>
            <h1 className="page-title">Admin panel</h1>
            <p className="page-sub">Accounts, subscriptions and license keys.</p>
          </div>
          <button className="btn btn-soft" type="button" onClick={() => void load()}>
            <Icon name="refresh" size={17} /> Refresh
          </button>
        </div>

        <div className="admin-stats">
          <div className="stat-card accent"><div className="stat-value">{stats.total}</div><div className="stat-label">Registered accounts</div></div>
          <div className="stat-card"><div className="stat-value">{stats.active}</div><div className="stat-label">Active subscriptions</div></div>
          <div className="stat-card"><div className="stat-value">{stats.trialClaims}</div><div className="stat-label">Trials claimed</div></div>
          <div className="stat-card"><div className="stat-value">{stats.blocked}</div><div className="stat-label">Blocked</div></div>
        </div>

        <div className="admin-grid">
          <div>
            <Card variant="outlined" sx={{ borderRadius: 2, mb: 1.5 }}>
              <CardContent>
                <div className="row-title" style={{ marginBottom: 10, display: 'flex', alignItems: 'center', gap: 8 }}>
                  <Icon name="key" size={18} /> Generate license keys
                </div>
                <div style={{ display: 'flex', flexDirection: 'column', gap: 10 }}>
                  <Select size="small" value={kind} onChange={(event) => setKind(event.target.value as KindKey)} fullWidth>
                    {(Object.keys(KEY_KIND) as KindKey[]).map((keyItem) => (
                      <MenuItem key={keyItem} value={keyItem}>{KEY_KIND[keyItem].label}</MenuItem>
                    ))}
                  </Select>
                  <div style={{ fontSize: 11.5, color: 'var(--text-3)' }}>{KEY_KIND[kind].hint}</div>
                  {kind === 'custom' ? (
                    <TextField
                      size="small" type="number" label="Days" value={days}
                      onChange={(event) => setDays(Math.max(1, Number(event.target.value) || 1))}
                      slotProps={{ htmlInput: { min: 1, max: 3650 } }} fullWidth
                    />
                  ) : null}
                  <div style={{ display: 'flex', gap: 10 }}>
                    <TextField
                      size="small" type="number" label="How many" value={count}
                      onChange={(event) => setCount(Math.max(1, Math.min(50, Number(event.target.value) || 1)))}
                      slotProps={{ htmlInput: { min: 1, max: 50 } }} sx={{ width: 128 }}
                    />
                    <MuiButton variant="contained" onClick={() => void generate()} disabled={busy} sx={{ flex: 1 }}>
                      {busy ? <CircularProgress size={20} color="inherit" /> : 'Generate'}
                    </MuiButton>
                  </div>
                </div>
                {created.length > 0 ? (
                  <div style={{ marginTop: 12 }}>
                    <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center', marginBottom: 6 }}>
                      <b style={{ fontSize: 12, color: 'var(--text-2)' }}>New keys — copy them now, they are shown once</b>
                      <MuiButton size="small" onClick={() => void copy(created.map((entry) => entry.code).join('\n'))}>Copy all</MuiButton>
                    </div>
                    <div className="atable-wrap" style={{ maxHeight: 220, overflowY: 'auto' }}>
                      {created.map((entry) => (
                        <div key={entry.id} style={{ display: 'flex', alignItems: 'center', gap: 8, padding: '6px 8px', borderBottom: '1px solid var(--line-soft)' }}>
                          <code className="code-chip" style={{ flex: 1, overflow: 'hidden', textOverflow: 'ellipsis' }}>{entry.code}</code>
                          <MuiButton size="small" onClick={() => void copy(entry.code)}>Copy</MuiButton>
                        </div>
                      ))}
                    </div>
                  </div>
                ) : null}
              </CardContent>
            </Card>

            <Card variant="outlined" sx={{ borderRadius: 2 }}>
              <CardContent>
                <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center', marginBottom: 8 }}>
                  <div className="row-title" style={{ display: 'flex', alignItems: 'center', gap: 8 }}><Icon name="key" size={18} /> Outstanding keys</div>
                  <Chip size="small" label={`${outstanding.length} active`} color="primary" variant="outlined" />
                </div>
                {outstanding.length === 0 ? (
                  <div style={{ fontSize: 12, color: 'var(--text-3)', padding: '6px 2px' }}>No unredeemed keys. Generate some above.</div>
                ) : (
                  <div style={{ maxHeight: 220, overflowY: 'auto' }}>
                    <Table size="small">
                      <TableHead>
                        <TableRow><TableCell>Created</TableCell><TableCell>Type</TableCell><TableCell>Duration</TableCell><TableCell align="right">Revoke</TableCell></TableRow>
                      </TableHead>
                      <TableBody>
                        {outstanding.map((code) => (
                          <TableRow key={code.id}>
                            <TableCell>{fmtDate(code.createdAt)}</TableCell>
                            <TableCell><Chip size="small" label={code.kind} /></TableCell>
                            <TableCell>{Math.round(code.durationSeconds / 86400)} days</TableCell>
                            <TableCell align="right"><MuiButton size="small" color="error" onClick={() => void revoke(code)}>Revoke</MuiButton></TableCell>
                          </TableRow>
                        ))}
                      </TableBody>
                    </Table>
                  </div>
                )}
              </CardContent>
            </Card>
          </div>

          <Card variant="outlined" sx={{ borderRadius: 2 }}>
            <CardContent>
              <div className="admin-toolbar">
                <div className="row-title" style={{ display: 'flex', alignItems: 'center', gap: 8, marginRight: 'auto' }}><Icon name="profiles" size={18} /> Accounts</div>
                <TextField size="small" placeholder="Search email…" value={search} onChange={(event) => setSearch(event.target.value)} sx={{ width: 210 }} />
              </div>
              <div className="atable-wrap" style={{ maxHeight: 520, overflowY: 'auto', border: 0, background: 'transparent' }}>
                <Table size="small" stickyHeader>
                  <TableHead>
                    <TableRow>
                      <TableCell>Email</TableCell>
                      <TableCell>Plan</TableCell>
                      <TableCell>Expires</TableCell>
                      <TableCell>Status</TableCell>
                      <TableCell align="right">Manage</TableCell>
                    </TableRow>
                  </TableHead>
                  <TableBody>
                    {visibleUsers.map((user) => {
                      const left = daysLeft(user.expiresAt);
                      const active = left !== null && left > 0;
                      return (
                        <TableRow key={user.userId}>
                          <TableCell>
                            <div style={{ fontWeight: 600 }}>{user.email}</div>
                            <div style={{ fontSize: 10.5, color: 'var(--text-3)' }}>joined {fmtDate(user.createdAt)}</div>
                          </TableCell>
                          <TableCell>{user.expiresAt ? <Chip size="small" label={user.plan ?? 'premium'} color={user.plan === 'trial' ? 'success' : 'primary'} variant="outlined" /> : <Chip size="small" label="none" variant="outlined" />}</TableCell>
                          <TableCell>
                            {fmtDate(user.expiresAt)}
                            {active ? <div style={{ fontSize: 10.5, color: 'var(--ok)' }}>{left} days left</div> : user.expiresAt ? <div style={{ fontSize: 10.5, color: 'var(--err)' }}>expired</div> : null}
                          </TableCell>
                          <TableCell>{user.isBlocked ? <Chip size="small" color="error" label="blocked" /> : <Chip size="small" variant="outlined" label="ok" />}</TableCell>
                          <TableCell align="right">
                            <div style={{ display: 'inline-flex', gap: 4, flexWrap: 'wrap', justifyContent: 'flex-end' }}>
                              <Tooltip title="Add 31 days"><MuiButton size="small" onClick={() => void extend(user, 31)}>+31d</MuiButton></Tooltip>
                              <Tooltip title="Add 365 days"><MuiButton size="small" onClick={() => void extend(user, 365)}>+1y</MuiButton></Tooltip>
                              <MuiButton size="small" onClick={() => setExpiryDialog({ user, value: new Date(user.expiresAt ?? Date.now()).toISOString().slice(0, 16) })}>Set date</MuiButton>
                              <MuiButton size="small" color={user.isBlocked ? 'success' : 'error'} onClick={() => void toggleBlock(user)}>
                                {user.isBlocked ? 'Unblock' : 'Block'}
                              </MuiButton>
                            </div>
                          </TableCell>
                        </TableRow>
                      );
                    })}
                    {visibleUsers.length === 0 ? (
                      <TableRow><TableCell colSpan={5} align="center" sx={{ color: 'var(--text-3)', py: 3 }}>No accounts match “{search}”.</TableCell></TableRow>
                    ) : null}
                  </TableBody>
                </Table>
              </div>
            </CardContent>
          </Card>
        </div>
      </div>

      <Dialog open={expiryDialog !== null} onClose={() => setExpiryDialog(null)} maxWidth="xs" fullWidth>
        <DialogTitle>Set subscription date</DialogTitle>
        <DialogContent>
          <div style={{ fontSize: 12.5, color: 'var(--text-2)', marginBottom: 10 }}>{expiryDialog?.user.email}</div>
          <TextField
            type="datetime-local"
            label="Access until"
            value={expiryDialog?.value ?? ''}
            onChange={(event) => setExpiryDialog((current) => (current ? { ...current, value: event.target.value } : current))}
            fullWidth
            slotProps={{ inputLabel: { shrink: true } }}
            autoFocus
          />
        </DialogContent>
        <DialogActions>
          <MuiButton onClick={() => setExpiryDialog(null)}>Cancel</MuiButton>
          <MuiButton variant="contained" onClick={() => void saveExpiry()}>Save</MuiButton>
        </DialogActions>
      </Dialog>
    </div>
  );
}
